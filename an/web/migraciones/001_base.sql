-- Esquema base de An (PostgreSQL). Las columnas de negocio replican an/turnos/db.py; clinica_id y area_id van AL FINAL para que
-- los INSERT … VALUES posicionales del núcleo sigan valiendo. Una migración publicada no se edita: se agrega otra.

CREATE TABLE clinica (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL, creada timestamptz NOT NULL DEFAULT now());

CREATE TABLE area (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL, tipo text NOT NULL DEFAULT 'turnos' CHECK (tipo IN ('turnos', 'radiologia')),
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id), UNIQUE (clinica_id, nombre));

ALTER TABLE clinica ENABLE ROW LEVEL SECURITY;
ALTER TABLE clinica FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON clinica USING (id = current_setting('app.clinica')::bigint);

