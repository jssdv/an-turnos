-- Usuarios, permisos por área, sesiones, intentos de ingreso y auditoría.
CREATE TABLE usuario (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo text NOT NULL UNIQUE CHECK (correo = lower(correo)),
  nombre text NOT NULL,
  hash_clave text NOT NULL,
  es_admin boolean NOT NULL DEFAULT false,
  activo boolean NOT NULL DEFAULT true,
  debe_cambiar boolean NOT NULL DEFAULT true,
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id)
);
ALTER TABLE usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON usuario USING (clinica_id = current_setting('app.clinica')::bigint);

CREATE TABLE usuario_area (
  usuario_id bigint NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  area_id bigint NOT NULL REFERENCES area(id) ON DELETE CASCADE,
  permiso text NOT NULL CHECK (permiso IN ('ver', 'editar')),
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id),
  PRIMARY KEY (usuario_id, area_id)
);
-- un solo usuario edita por área; los demás solo ven
CREATE UNIQUE INDEX un_editor_por_area ON usuario_area (area_id) WHERE permiso = 'editar';
ALTER TABLE usuario_area ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario_area FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON usuario_area USING (clinica_id = current_setting('app.clinica')::bigint);

-- sesion e intento_login no se tocan directamente desde la aplicación: solo por funciones SECURITY DEFINER (an/web/auth.py)
CREATE TABLE sesion (
  hash_token text PRIMARY KEY,
  usuario_id bigint NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  creada timestamptz NOT NULL DEFAULT now(),
  ultima timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE intento_login (correo text NOT NULL, ip text NOT NULL, fecha timestamptz NOT NULL DEFAULT now());
CREATE INDEX ON intento_login (correo, ip, fecha);

CREATE TABLE auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha timestamptz NOT NULL DEFAULT now(),
  usuario_id bigint,
  correo text,
  metodo text NOT NULL,
  ruta text NOT NULL,
  codigo int NOT NULL,
  ip text,
  evento text,
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id)
);
ALTER TABLE auditoria ENABLE ROW LEVEL SECURITY;
ALTER TABLE auditoria FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON auditoria USING (clinica_id = current_setting('app.clinica')::bigint);

DO $$ BEGIN
  EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON usuario, usuario_area TO an_app');
  EXECUTE format('GRANT SELECT, INSERT ON auditoria TO an_app');
  EXECUTE format('GRANT USAGE ON ALL SEQUENCES IN SCHEMA %I TO an_app', current_schema());
END $$;

-- Funciones de ingreso: SECURITY DEFINER para poder buscar usuario y sesión antes de conocer la clínica.
-- El dueño de estas funciones debe poder saltarse RLS (superusuario o BYPASSRLS): es el rol que aplica las migraciones.
DO $$
DECLARE sp text := format('SET search_path = %I, pg_temp', current_schema());
BEGIN
  EXECUTE 'CREATE FUNCTION app_buscar_usuario(p_correo text) RETURNS TABLE (id bigint, clinica_id bigint, nombre text, hash_clave text,
             es_admin boolean, activo boolean, debe_cambiar boolean) LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             SELECT u.id, u.clinica_id, u.nombre, u.hash_clave, u.es_admin, u.activo, u.debe_cambiar FROM usuario u WHERE u.correo = lower(p_correo) $f$';
  EXECUTE 'CREATE FUNCTION app_intentos(p_correo text, p_ip text) RETURNS int LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             SELECT count(*)::int FROM intento_login WHERE correo = lower(p_correo) AND ip = p_ip AND fecha > now() - interval ''15 minutes'' $f$';
  EXECUTE 'CREATE FUNCTION app_registrar_intento(p_correo text, p_ip text) RETURNS void LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             INSERT INTO intento_login (correo, ip) VALUES (lower(p_correo), p_ip) $f$';
  EXECUTE 'CREATE FUNCTION app_limpiar_intentos(p_correo text, p_ip text) RETURNS void LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             DELETE FROM intento_login WHERE correo = lower(p_correo) AND ip = p_ip $f$';
  EXECUTE 'CREATE FUNCTION app_crear_sesion(p_hash text, p_usuario bigint) RETURNS void LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             INSERT INTO sesion (hash_token, usuario_id) VALUES (p_hash, p_usuario) $f$';
  -- devuelve el usuario de la sesión si no venció (35 min sin uso o 12 h desde que se creó) y le renueva `ultima`; la hora es la del servidor
  EXECUTE 'CREATE FUNCTION app_sesion(p_hash text) RETURNS TABLE (id bigint, clinica_id bigint, correo text, nombre text,
             es_admin boolean, debe_cambiar boolean) LANGUAGE plpgsql SECURITY DEFINER ' || sp || ' AS $f$
             DECLARE v_ahora timestamptz := clock_timestamp();
             BEGIN
               UPDATE sesion s SET ultima = v_ahora WHERE s.hash_token = p_hash
                 AND v_ahora - s.ultima < interval ''35 minutes'' AND v_ahora - s.creada < interval ''12 hours''
                 AND EXISTS (SELECT 1 FROM usuario u WHERE u.id = s.usuario_id AND u.activo);
               RETURN QUERY SELECT u.id, u.clinica_id, u.correo, u.nombre, u.es_admin, u.debe_cambiar
                 FROM sesion s JOIN usuario u ON u.id = s.usuario_id WHERE s.hash_token = p_hash AND s.ultima = v_ahora;
             END $f$';
  EXECUTE 'CREATE FUNCTION app_cerrar_sesion(p_hash text) RETURNS void LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             DELETE FROM sesion WHERE hash_token = p_hash $f$';
  EXECUTE 'CREATE FUNCTION app_hash_clave(p_usuario bigint) RETURNS text LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             SELECT hash_clave FROM usuario WHERE id = p_usuario AND clinica_id = current_setting(''app.clinica'')::bigint $f$';
  -- cambia la clave dentro de la clínica del alcance y cierra las demás sesiones del usuario (la que se conserva, si se indica, sigue viva)
  EXECUTE 'CREATE FUNCTION app_poner_clave(p_usuario bigint, p_hash text, p_conservar text DEFAULT NULL) RETURNS void LANGUAGE plpgsql
             SECURITY DEFINER ' || sp || ' AS $f$
             BEGIN
               UPDATE usuario SET hash_clave = p_hash, debe_cambiar = false
                 WHERE id = p_usuario AND clinica_id = current_setting(''app.clinica'')::bigint;
               IF FOUND THEN
                 DELETE FROM sesion WHERE usuario_id = p_usuario AND (p_conservar IS NULL OR hash_token <> p_conservar);
               END IF;
             END $f$';
  EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA %I FROM PUBLIC', current_schema());
  EXECUTE format('GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA %I TO an_app', current_schema());
END $$;
