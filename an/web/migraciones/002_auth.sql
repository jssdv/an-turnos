-- Usuarios, permisos por área, sesiones, intentos de ingreso y auditoría.
CREATE TABLE usuario (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo text NOT NULL UNIQUE CHECK (correo = lower(correo)),
  nombre text NOT NULL,
  hash_clave text NOT NULL,
  es_admin boolean NOT NULL DEFAULT false,
  activo boolean NOT NULL DEFAULT true,
  debe_cambiar boolean NOT NULL DEFAULT true,
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id)
);
ALTER TABLE usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON usuario USING (clinica_id = current_setting('app.clinica')::bigint);

CREATE TABLE usuario_area (
  usuario_id bigint NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  area_id bigint NOT NULL REFERENCES area(id) ON DELETE CASCADE,
  permiso text NOT NULL CHECK (permiso IN ('ver', 'editar')),
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id),
  PRIMARY KEY (usuario_id, area_id)
);
-- un solo usuario edita por área; los demás solo ven
CREATE UNIQUE INDEX un_editor_por_area ON usuario_area (area_id) WHERE permiso = 'editar';
ALTER TABLE usuario_area ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario_area FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON usuario_area USING (clinica_id = current_setting('app.clinica')::bigint);

-- sesion e intento_login no se tocan directamente desde la aplicación: solo por funciones SECURITY DEFINER (an/web/auth.py)
CREATE TABLE sesion (
  hash_token text PRIMARY KEY,
  usuario_id bigint NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  creada timestamptz NOT NULL DEFAULT now(),
  ultima timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE intento_login (correo text NOT NULL, ip text NOT NULL, fecha timestamptz NOT NULL DEFAULT now());
CREATE INDEX ON intento_login (correo, ip, fecha);

CREATE TABLE auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha timestamptz NOT NULL DEFAULT now(),
  usuario_id bigint,
  correo text,
  metodo text NOT NULL,
  ruta text NOT NULL,
  codigo int NOT NULL,
  ip text,
  evento text,
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id)
);
ALTER TABLE auditoria ENABLE ROW LEVEL SECURITY;
ALTER TABLE auditoria FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON auditoria USING (clinica_id = current_setting('app.clinica')::bigint);

