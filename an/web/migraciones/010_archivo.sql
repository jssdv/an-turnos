-- Cuadro mensual de Radiología subido como .xlsx (Fase 7b; deja de usarse cuando Radiología se genere sola, Fase 7c).
CREATE TABLE archivo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  contenido bytea NOT NULL,
  subido_por bigint REFERENCES usuario(id),
  subido timestamptz NOT NULL DEFAULT now(),
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id),
  area_id bigint NOT NULL DEFAULT current_setting('app.area')::bigint REFERENCES area(id)
);
CREATE INDEX ON archivo (area_id, subido DESC);
ALTER TABLE archivo ENABLE ROW LEVEL SECURITY;
ALTER TABLE archivo FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON archivo USING (clinica_id = current_setting('app.clinica')::bigint AND area_id = current_setting('app.area')::bigint);

DO $$
BEGIN
  EXECUTE 'GRANT SELECT, INSERT, DELETE ON archivo TO an_app';
  EXECUTE format('GRANT USAGE ON ALL SEQUENCES IN SCHEMA %I TO an_app', current_schema());
END $$;
