-- Exportes en Excel de un periodo (Fase 6). Solo se agregan: un exporte nunca se reemplaza ni se borra (numero = máximo + 1 por área, periodo y tipo).
CREATE TABLE exporte (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id),
  area_id bigint NOT NULL DEFAULT current_setting('app.area')::bigint REFERENCES area(id),
  periodo_id bigint NOT NULL REFERENCES periodo(id) ON DELETE CASCADE,
  tipo text NOT NULL CHECK (tipo IN ('cuadro', 'puestos', 'horas', 'semana')),
  numero int NOT NULL CHECK (numero >= 1),
  nombre_archivo text NOT NULL,
  contenido bytea NOT NULL,
  creado_por bigint REFERENCES usuario(id),
  creado timestamptz NOT NULL DEFAULT now(),
  UNIQUE (area_id, periodo_id, tipo, numero)
);
ALTER TABLE exporte ENABLE ROW LEVEL SECURITY;
ALTER TABLE exporte FORCE ROW LEVEL SECURITY;
CREATE POLICY aislamiento ON exporte USING (clinica_id = current_setting('app.clinica')::bigint AND area_id = current_setting('app.area')::bigint);

DO $$ BEGIN
  EXECUTE format('GRANT SELECT, INSERT ON exporte TO an_app');
  EXECUTE format('GRANT USAGE ON ALL SEQUENCES IN SCHEMA %I TO an_app', current_schema());
END $$;
