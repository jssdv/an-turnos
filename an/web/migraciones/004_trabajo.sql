-- Cola de trabajos del solver: una tabla; un trabajo activo (en_cola|corriendo) por clínica.
CREATE TABLE trabajo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo_id bigint NOT NULL REFERENCES periodo(id),
  tipo text NOT NULL CHECK (tipo IN ('generar', 'dotacion')),
  params jsonb NOT NULL DEFAULT '{}',
  revision_base int NOT NULL,
  estado text NOT NULL DEFAULT 'en_cola' CHECK (estado IN ('en_cola', 'corriendo', 'listo', 'fallido', 'cancelado', 'conflicto')),
  progreso jsonb,
  cancelar boolean NOT NULL DEFAULT false,
  latido timestamptz,
  resultado jsonb,
  error text,
  creado_por bigint REFERENCES usuario(id),
  creado timestamptz NOT NULL DEFAULT now(),
  terminado timestamptz,
  clinica_id bigint NOT NULL DEFAULT current_setting('app.clinica')::bigint REFERENCES clinica(id),
  area_id bigint NOT NULL DEFAULT current_setting('app.area')::bigint REFERENCES area(id)
);
CREATE UNIQUE INDEX un_trabajo_activo_por_clinica ON trabajo (clinica_id) WHERE estado IN ('en_cola', 'corriendo');
CREATE INDEX ON trabajo (estado, creado);
ALTER TABLE trabajo ENABLE ROW LEVEL SECURITY;
ALTER TABLE trabajo FORCE ROW LEVEL SECURITY;
-- solo por clínica: el 409 de «ya hay un cuadro generándose» debe ver los trabajos de todas las áreas; el permiso por área lo comprueban las rutas
CREATE POLICY aislamiento ON trabajo USING (clinica_id = current_setting('app.clinica')::bigint);

DO $$
DECLARE sp text := format('SET search_path = %I, pg_temp', current_schema());
BEGIN
  EXECUTE format('GRANT SELECT, INSERT, UPDATE ON trabajo TO an_app');
  EXECUTE format('GRANT USAGE ON ALL SEQUENCES IN SCHEMA %I TO an_app', current_schema());
  -- El trabajador aún no conoce la clínica: toma el trabajo más antiguo sin alcance. El dueño debe saltarse RLS (como en 002_auth.sql).
  EXECUTE 'CREATE FUNCTION app_tomar_trabajo() RETURNS TABLE (id bigint, clinica_id bigint, area_id bigint, periodo_id bigint, tipo text,
             params jsonb, revision_base int) LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             UPDATE trabajo t SET estado = ''corriendo'', latido = clock_timestamp()
               WHERE t.id = (SELECT q.id FROM trabajo q WHERE q.estado = ''en_cola'' ORDER BY q.creado, q.id FOR UPDATE SKIP LOCKED LIMIT 1)
               RETURNING t.id, t.clinica_id, t.area_id, t.periodo_id, t.tipo, t.params, t.revision_base $f$';
  -- lo que sigue «corriendo» sin latido reciente es de un proceso que murió
  EXECUTE 'CREATE FUNCTION app_marcar_fallidos(p_segundos double precision) RETURNS int LANGUAGE sql SECURITY DEFINER ' || sp || ' AS $f$
             WITH u AS (UPDATE trabajo SET estado = ''fallido'', error = ''Se interrumpió; vuelve a generar.'', terminado = clock_timestamp()
               WHERE estado = ''corriendo'' AND latido < clock_timestamp() - make_interval(secs => p_segundos) RETURNING 1)
             SELECT count(*)::int FROM u $f$';
  EXECUTE 'REVOKE ALL ON FUNCTION app_tomar_trabajo() FROM PUBLIC';
  EXECUTE 'REVOKE ALL ON FUNCTION app_marcar_fallidos(double precision) FROM PUBLIC';
  EXECUTE 'GRANT EXECUTE ON FUNCTION app_tomar_trabajo() TO an_app';
  EXECUTE 'GRANT EXECUTE ON FUNCTION app_marcar_fallidos(double precision) TO an_app';
END $$;
